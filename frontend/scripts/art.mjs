#!/usr/bin/env node
// Builds assets/art/artSvgs.ts from every .svg under assets/art/: the drawings from the Figma frames as strings, so
// `<Art name="snap/treat-bowl" />` renders on the web and in the native app alike (react-native-svg, no loader needed).
//
//   node scripts/art.mjs          # write the module
//   node scripts/art.mjs --check  # exit 1 if it is stale (CI)
//
// A new drawing: drop the .svg in assets/art/<screen>/, run this, use `<Art name="<screen>/<file>" />`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "assets", "art");
const out = path.join(root, "artSvgs.ts");

function walk(dir, found = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, found);
    else if (e.name.endsWith(".svg")) found.push(p);
  }
  return found;
}

// Figma exports a `style="display: block;"` on the root; react-native-svg has no use for it.
const clean = (xml) => xml.replace(/\sstyle="[^"]*"/g, "").replace(/\n\s*/g, "").trim();

const files = walk(root).sort();
const lines = files.map((f) => {
  const name = path.relative(root, f).replace(/\.svg$/, "").split(path.sep).join("/");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(clean(fs.readFileSync(f, "utf8")))},`;
});
const body = `// Generated by scripts/art.mjs from the .svg files next to it. Do not edit.\nexport const ART = {\n${lines.join("\n")}\n} as const;\n\nexport type ArtName = keyof typeof ART;\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== body) {
    console.error("assets/art/artSvgs.ts is stale: run `node scripts/art.mjs`.");
    process.exit(1);
  }
  console.log("Art module is current.");
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote assets/art/artSvgs.ts — ${files.length} drawings`);
}
