"""Bundle the plugin: src/*.js -> code.js; data/screens-*.json -> ui.html (the plugin window).

1. Serve the prototypes (python3 -m http.server 4001 --directory design/concept-prototypes)
2. Re-capture screens (see README)
3. python3 design/figma-plugin/build.py
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
# Redesign (live app tabs): Live screenshots + Balanced + Playful. Calm Core (A) was dropped on Oct 5.
data = json.loads((HERE / "data" / "redesign.json").read_text()) if (HERE / "data" / "redesign.json").exists() else []
# Only the Live screenshots come from captured data; every other screen is built from components in the plugin.
data = [d for d in data if d.get("concept") == "Live"]
# Expressive (the Draft's look): every screen of the Prototype tab, captured by capture/expressive.spec.ts.
if (HERE / "data" / "expressive.json").exists():
    data = json.loads((HERE / "data" / "expressive.json").read_text()) + data
# Sample pet photo (Max) for the photo slots in components.
import base64
photo = HERE.parent / "concept-prototypes" / "redesign" / "img" / "pet0.jpg"
if photo.exists():
    data.insert(0, {"concept": "_samples", "label": "", "screens": [], "images": {"max": "data:image/jpeg;base64," + base64.b64encode(photo.read_bytes()).decode()}})
# The design tickets' slot (concept-prototypes/design-tickets.js): the same list the Project page and the daily update show.
tk_src = HERE.parent / "concept-prototypes" / "design-tickets.js"
design_tickets = tk_src.read_text().split("window.GOLDITO_TICKETS = ", 1)[1].rstrip().rstrip(";") if tk_src.exists() else '{"checked": "", "tickets": []}'
# What each Expressive component looked like before the plugin started tracking components (Oct 23), so the first
# tracked run can still flag what changed. Ignored once the file has its own record (figma.root "xcompMeta").
xbase = (HERE / "data" / "xcomp-baseline.json").read_text() if (HERE / "data" / "xcomp-baseline.json").exists() else "{}"
# Pets 360 sprite sheets (design/pixel-bodies/tama360.py) for the Dev reference page.
pets360 = (HERE / "data" / "pets360.json").read_text() if (HERE / "data" / "pets360.json").exists() else "null"
code = "\n".join(["/* Generated by build.py — edit src/, not this file. */", f"const DESIGN_TICKETS = {design_tickets};", f"const XCOMP_BASELINE = {xbase};", f"const PETS360 = {pets360};"] + [(HERE / "src" / f).read_text() for f in ("icons-data.js", "screens.js", "components.js", "foundations.js", "compose.js", "brand.js", "tickets.js", "devref.js", "decisions-data.js", "decisions.js", "main.js")])
(HERE / "code.js").write_text(code)
payload = json.dumps(data, separators=(",", ":")).replace("</", "<\\/")
brand = (HERE / "data" / "brand.json").read_text().replace("</", "<\\/") if (HERE / "data" / "brand.json").exists() else "null"
# Ticket workbenches (capture/tickets.spec.ts): decided frames, decisions and spec for the Tickets tab.
tickets = (HERE / "data" / "tickets.json").read_text().replace("</", "<\\/") if (HERE / "data" / "tickets.json").exists() else "null"
ui = (HERE / "src" / "ui.html").read_text().replace("/*DATA*/null", payload).replace("/*BRAND*/null", brand).replace("/*TICKETS*/null", tickets)
(HERE / "ui.html").write_text(ui)
print(f"code.js {len(code) // 1024} KB · ui.html {len(ui) // 1024} KB · {sum(len(d['screens']) for d in data)} screens")
